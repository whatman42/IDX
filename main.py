def normalize_horizon(raw) -> str:
    if raw is None:
        return "SHORT"
    s = str(raw).strip().upper()
    if s in VALID_HORIZONS:
        return s
    try:
        d = float(s)
        if d <= 2:
            return "SHORT"
        if d <= 10:
            return "MEDIUM"
        return "LONG"
    except Exception:
        return "SHORT"


